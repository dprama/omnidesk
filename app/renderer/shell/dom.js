// Tiny DOM helpers. No inline styles anywhere (CSP): use setProperty for dynamic values.

export const $ = (sel, root = document) => root.querySelector(sel);
export const $$ = (sel, root = document) => Array.from(root.querySelectorAll(sel));

/**
 * h('div.card', { 'aria-label': 'x', onclick: fn }, child, 'text', ...)
 * Attributes starting with "on" become listeners; `vars` sets CSS custom properties.
 */
export function h(tag, attrs, ...children) {
  const [name, ...classes] = tag.split('.');
  const el = document.createElement(name || 'div');
  if (classes.length) el.className = classes.join(' ');
  if (attrs) {
    for (const [k, v] of Object.entries(attrs)) {
      if (v == null || v === false) continue;
      if (k === 'vars') { for (const [p, val] of Object.entries(v)) el.style.setProperty(p, val); }
      else if (k.startsWith('on') && typeof v === 'function') el.addEventListener(k.slice(2), v);
      else if (k === 'class') el.className += (el.className ? ' ' : '') + v;
      else el.setAttribute(k, v === true ? '' : String(v));
    }
  }
  append(el, children);
  return el;
}

function append(el, children) {
  for (const c of children) {
    if (c == null || c === false) continue;
    if (Array.isArray(c)) append(el, c);
    else el.append(c instanceof Node ? c : document.createTextNode(String(c)));
  }
}

/** Sets textContent only when it changed (keeps live regions quiet). */
export function setText(el, text) {
  const t = String(text);
  if (el.textContent !== t) el.textContent = t;
}
